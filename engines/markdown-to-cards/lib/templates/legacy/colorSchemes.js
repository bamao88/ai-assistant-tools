export function normalizeColorScheme(value) {
  const raw = String(value || "").trim();
  if (!raw) return null;

  const key = raw.toLowerCase();
  const id = COLOR_SCHEME_ALIASES[key] || key;
  if (COLOR_SCHEME_IDS.includes(id)) return id;
  throw new Error(`Unknown color_scheme: ${value}. Available legacy schemes: ${COLOR_SCHEME_IDS.join(", ")}`);
}

export function resolveColorScheme(value) {
  const id = normalizeColorScheme(value);
  return id ? { id, ...COLOR_SCHEME_DEFS[id] } : null;
}
